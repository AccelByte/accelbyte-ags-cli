/// Controls how the executor pauses between workflow steps.
///
/// - `ReviewInputSteps`: pauses only when the step has reviewable or missing
///   required inputs (today's default; equivalent to the legacy gate).
/// - `ReviewEveryStep`: pauses before every step regardless of its field state.
/// - `RunWithoutStopping`: never pauses; missing required inputs are gathered
///   with plain-mode semantics (same as a non-review gather pass).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RunMode {
    /// Pause only when the step has reviewable or unset required fields.
    #[default]
    ReviewInputSteps,
    /// Pause before every step in the workflow.
    ReviewEveryStep,
    /// Never pause; gather missing required inputs without a review stop.
    RunWithoutStopping,
}

